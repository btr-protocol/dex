#!/usr/bin/env bun
/**
 * @title Generate Poseidon Contracts
 * @notice Generates Solidity contracts for Poseidon hash using circomlibjs
 * @dev Uses official iden3 circomlibjs to generate gas-efficient Poseidon contracts
 */

import { buildPoseidon } from "circomlibjs";
import { writeFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Output directory
const OUTPUT_DIR = resolve(__dirname, "../../contracts/src/darkpool/libraries/generated");

// Ensure output directory exists
mkdirSync(OUTPUT_DIR, { recursive: true });

async function generatePoseidonContracts() {
  console.log("🔨 Generating Poseidon Solidity contracts...\n");

  try {
    // Build Poseidon instance
    const poseidon = await buildPoseidon();

    // Generate contracts for T=2, T=3, T=4, T=5, T=6
    // T = number of inputs + 1 (includes capacity element)
    const variants = [
      { t: 2, name: "PoseidonT2" }, // Hash 1 input
      { t: 3, name: "PoseidonT3" }, // Hash 2 inputs (used for merkle tree)
      { t: 4, name: "PoseidonT4" }, // Hash 3 inputs
      { t: 5, name: "PoseidonT5" }, // Hash 4 inputs
      { t: 6, name: "PoseidonT6" }, // Hash 5 inputs
      { t: 9, name: "PoseidonT9" }, // Hash 8 inputs (used for commitments)
    ];

    for (const variant of variants) {
      console.log(`Generating ${variant.name} (T=${variant.t})...`);

      const contract = generatePoseidonContract(variant.t, variant.name, poseidon);
      const filePath = resolve(OUTPUT_DIR, `${variant.name}.sol`);

      writeFileSync(filePath, contract, "utf8");
      console.log(`✅ ${variant.name}.sol written to ${filePath}\n`);
    }

    // Generate main Poseidon library that wraps all variants
    console.log("Generating Poseidon library wrapper...");
    const wrapperContract = generatePoseidonWrapper();
    const wrapperPath = resolve(OUTPUT_DIR, "Poseidon.sol");

    writeFileSync(wrapperPath, wrapperContract, "utf8");
    console.log(`✅ Poseidon.sol written to ${wrapperPath}\n`);

    console.log("🎉 All Poseidon contracts generated successfully!");
    console.log("\n📋 Next steps:");
    console.log("1. Review generated contracts in contracts/src/darkpool/libraries/generated/");
    console.log("2. Update LibMerkleTree.sol to import and use Poseidon.hash2()");
    console.log("3. Run: bun run generate-zeros to generate zero values");
  } catch (error) {
    console.error("❌ Error generating Poseidon contracts:", error);
    process.exit(1);
  }
}

